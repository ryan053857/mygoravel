// Package clientgen 从 rest 登记的端点生成 Go 和 TypeScript 客户端。
//
// 生成的客户端按 operationId 分组（article-publish 生成 Client.Article.Publish），
// 接口用到的类型按服务端的包复制（internal/article.Changes 生成为 <out>/article.Changes），
// errorx.Define 定义的错误码生成为可以用 errors.Is 判断的常量。生成的代码只依赖标准库、
// 允许直接导入的包（默认 github.com/google/uuid）和随代码生成的运行时 <out>/wire，不依赖 Tenon。
//
// GenerateTS 生成 TypeScript 客户端：类型取自 OpenAPI 文档，分组和错误码与 Go 客户端相同，运行时随代码生成，
// 不依赖任何 npm 包。
package clientgen

import (
	_ "embed"
	"go/ast"
	"go/parser"
	"go/token"
	"go/types"
	"os"
	"path"
	"path/filepath"
	"reflect"
	"slices"
	"strings"

	"github.com/cockroachdb/errors"
	"golang.org/x/mod/modfile"
	"golang.org/x/tools/go/packages"

	"github.com/go-tenon/tenon/httpx/rest"
)

// Header 是生成的每个文件的第一行；Write 只删除带这一行的旧文件。
const Header = "// Code generated by tenon client. DO NOT EDIT."

//go:embed wire/wire.go
var wireSource string

// Options 配置生成。
type Options struct {
	// Out 是输出目录，必须位于某个 Go 模块中；目录名就是根包的包名，例如 api。
	Out string
	// Main 是应用的主包（导入路径或相对 Dir 的模式，例如 ./cmd/api）。在它依赖的、属于应用模块和
	// Tenon 的包中查找 errorx.Define 定义的错误码。
	Main string
	// Dir 是加载源码的工作目录，空表示当前目录。
	Dir string
	// Imports 是在标准库和 github.com/google/uuid 之外，客户端可以直接导入、不必复制的包，
	// 也包括它们的子包，例如 github.com/uptrace/bun 也允许 github.com/uptrace/bun/schema。
	Imports []string
	// Rename 把服务端包的导入路径映射为镜像包名，用于两个包同名的情况。
	Rename map[string]string
}

// Result 是生成结果。
type Result struct {
	// Files 是相对 Out 的文件路径到内容。
	Files map[string][]byte
	// Skipped 列出没有生成的端点及原因。
	Skipped []string
}

// defaultImports 是总是可以直接导入的第三方包。
var defaultImports = []string{"github.com/google/uuid"}

// frameworkModule 是 Tenon 的模块路径。
var frameworkModule = strings.TrimSuffix(reflect.TypeFor[rest.API]().PkgPath(), "/httpx/rest")

// Generate 生成 api 中端点的客户端代码，不写入磁盘，见 Write。
func Generate(api *rest.API, opts Options) (*Result, error) {
	if opts.Out == "" || opts.Main == "" {
		return nil, errors.New("clientgen: Out and Main are required")
	}
	g, err := newGenerator(api, opts)
	if err != nil {
		return nil, err
	}
	return g.run()
}

type generator struct {
	api      *rest.API
	opts     Options
	outPath  string // Out 的导入路径
	rootName string // 根包的包名

	fset    *token.FileSet
	pkgs    map[string]*packages.Package
	main    *packages.Package
	modules map[string]bool // 类型可以复制的模块
	imports map[string]bool // 可以直接导入的非标准库包

	mirrors map[string]*mirror // 服务端包路径 → 镜像包
	names   map[string]string  // 镜像包名 → 服务端包路径
	queue   []*types.TypeName
	seen    map[*types.TypeName]bool
	docs    map[string]map[token.Pos]string // 包路径 → 声明位置 → 注释
}

func newGenerator(api *rest.API, opts Options) (*generator, error) {
	outPath, err := importPath(opts.Out)
	if err != nil {
		return nil, err
	}
	rootName := path.Base(outPath)
	if !token.IsIdentifier(rootName) {
		return nil, errors.Newf("clientgen: output directory name %q is not a valid package name", rootName)
	}
	g := &generator{
		api: api, opts: opts, outPath: outPath, rootName: rootName,
		fset:    token.NewFileSet(),
		pkgs:    map[string]*packages.Package{},
		modules: map[string]bool{frameworkModule: true},
		imports: map[string]bool{},
		mirrors: map[string]*mirror{},
		names:   map[string]string{"wire": "wire"},
		seen:    map[*types.TypeName]bool{},
		docs:    map[string]map[token.Pos]string{},
	}
	for _, p := range append(slices.Clone(defaultImports), opts.Imports...) {
		g.imports[p] = true
	}
	if err := g.load(); err != nil {
		return nil, err
	}
	return g, nil
}

// load 加载主包及其全部依赖的声明（不含函数体）。
func (g *generator) load() error {
	patterns := []string{g.opts.Main}
	for _, ep := range g.api.Endpoints() {
		for _, t := range endpointTypes(ep) {
			if p := t.PkgPath(); p != "" && !slices.Contains(patterns, p) {
				patterns = append(patterns, p)
			}
		}
	}
	cfg := &packages.Config{
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedImports | packages.NeedDeps |
			packages.NeedTypes | packages.NeedSyntax | packages.NeedTypesInfo | packages.NeedModule,
		Dir:  g.opts.Dir,
		Fset: g.fset,
		// 只需要声明：去掉函数体，加载快很多。去掉后出现的“导入未使用”等错误不影响声明的类型。
		ParseFile: func(fset *token.FileSet, filename string, src []byte) (*ast.File, error) {
			f, err := parser.ParseFile(fset, filename, src, parser.ParseComments|parser.SkipObjectResolution)
			if f != nil {
				for _, d := range f.Decls {
					if fd, ok := d.(*ast.FuncDecl); ok {
						fd.Body = nil
					}
				}
			}
			return f, err
		},
	}
	roots, err := packages.Load(cfg, patterns...)
	if err != nil {
		return errors.Wrap(err, "clientgen: load packages")
	}
	packages.Visit(roots, nil, func(p *packages.Package) { g.pkgs[p.PkgPath] = p })
	g.main = roots[0]
	if g.main.Types == nil || g.main.Module == nil {
		return errors.Newf("clientgen: cannot load main package %q: %v", g.opts.Main, g.main.Errors)
	}
	g.modules[g.main.Module.Path] = true
	return nil
}

func endpointTypes(ep rest.Endpoint) []reflect.Type {
	ts := []reflect.Type{ep.Input, ep.Output}
	for _, t := range ep.Events {
		ts = append(ts, t)
	}
	return ts
}

// lookup 找到 reflect 类型在源码中的声明。
func (g *generator) lookup(t reflect.Type) (*types.TypeName, error) {
	if t.Name() == "" || t.PkgPath() == "" {
		return nil, errors.Newf("clientgen: %s is not a named type", t)
	}
	if strings.Contains(t.Name(), "[") {
		return nil, errors.Newf("clientgen: generic input or output type %s is not supported", t)
	}
	p := g.pkgs[t.PkgPath()]
	if p == nil || p.Types == nil {
		return nil, errors.Newf("clientgen: package %s of %s is not loaded", t.PkgPath(), t)
	}
	obj, ok := p.Types.Scope().Lookup(t.Name()).(*types.TypeName)
	if !ok {
		return nil, errors.Newf("clientgen: type %s not found in source", t)
	}
	return obj, nil
}

// importPath 返回目录 dir 的导入路径：向上找到 go.mod，用模块路径加相对路径。
func importPath(dir string) (string, error) {
	abs, err := filepath.Abs(dir)
	if err != nil {
		return "", errors.Wrap(err, "clientgen")
	}
	for d := abs; ; d = filepath.Dir(d) {
		data, err := os.ReadFile(filepath.Join(d, "go.mod"))
		if err == nil {
			mod := modfile.ModulePath(data)
			if mod == "" {
				return "", errors.Newf("clientgen: %s has no module path", filepath.Join(d, "go.mod"))
			}
			rel, err := filepath.Rel(d, abs)
			if err != nil {
				return "", errors.Wrap(err, "clientgen")
			}
			if rel == "." {
				return mod, nil
			}
			return mod + "/" + filepath.ToSlash(rel), nil
		}
		if filepath.Dir(d) == d {
			return "", errors.Newf("clientgen: %s is not inside a Go module", dir)
		}
	}
}

// isStd 报告导入路径是不是标准库。
func isStd(p string) bool {
	first, _, _ := strings.Cut(p, "/")
	return !strings.Contains(first, ".")
}
