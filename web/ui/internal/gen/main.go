// gen 从 go.mod 中固定版本的 shadcn-templ 生成 web/ui 的前端资源，在 web/ui 目录中运行：go generate。
// 需要 tailwindcss（standalone CLI）。只有升级 shadcn-templ，或修改 css/ui.css、css/safelist.css、css/docs.css、
// js/glue.js、web/ui、web/docs 和 queue/queueweb 的 templ 组件中的类名后才需要运行。
//
// 生成：
//
//   - css/vendor/：上游的 tw-animate.css、shadcn-tailwind.css 和 8 套风格 styles/style-*.css；
//   - css/classes.txt：shadcn-templ 组件与 web/ui、web/docs、queue/queueweb 组件中的类名候选，供 Tailwind 扫描；
//   - css/docs-chroma.css：web/docs 代码块的高亮颜色；
//   - css/style-<风格>.css：每套风格的样式入口，导入 ui.css 和该风格；
//   - assets/：gzip 压缩的资源，文件名带内容哈希：
//     每套风格预编译的样式表（附带 css/safelist.css 中的常用工具类），
//     组件脚本的默认包（baseui 在前，逐个压缩后拼接，与 shadcn-templ bundle 相同），
//     按需加载的扩展组件脚本，衔接脚本 js/glue.js；
//   - manifest.go：上述文件名。
package main

import (
	"bytes"
	"compress/gzip"
	"crypto/sha256"
	"fmt"
	"go/format"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"strings"

	chromahtml "github.com/alecthomas/chroma/v2/formatters/html"
	"github.com/alecthomas/chroma/v2/styles"
	"github.com/evanw/esbuild/pkg/api"
)

const module = "github.com/axadrn/shadcn-templ/v2"

// extras 是不放进默认包、页面出现对应元素时才加载的组件：体积大且不常用。
// 选择器是组件的根元素（data-slot 或 lifecycle.register 的选择器）；升级时生成器检查它们仍然出现在组件的
// .templ 或脚本中。
var extras = []struct{ dir, selector string }{
	{"calendar", `[data-slot="calendar"]`},
	{"carousel", `[data-slot="carousel"]`},
	{"chart", `script[data-templ-chart-model]`},
	{"drawer", `[data-slot="drawer-viewport"]`},
	{"inputotp", `[data-input-otp-container]`},
	{"messagescroller", `[data-slot="message-scroller"]`},
	{"questionnaire", `[data-slot="questionnaire"]`},
	{"resizable", `[data-slot="resizable-panel-group"]`},
}

func main() {
	out, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}} {{.Version}}", module).Output()
	if err != nil {
		log.Fatalf("go list %s: %v", module, err)
	}
	dir, version, _ := strings.Cut(strings.TrimSpace(string(out)), " ")

	must(os.RemoveAll("css/vendor"))
	must(os.MkdirAll("css/vendor/styles", 0o755))
	for _, f := range []string{"tw-animate.css", "shadcn-tailwind.css"} {
		copyFile(filepath.Join(dir, "assets/css", f), filepath.Join("css/vendor", f))
	}
	styles, _ := filepath.Glob(filepath.Join(dir, "assets/css/styles/style-*.css"))
	if len(styles) == 0 {
		log.Fatal("no styles in shadcn-templ")
	}
	for _, f := range styles {
		copyFile(f, filepath.Join("css/vendor/styles", filepath.Base(f)))
	}
	writeClasses(dir)
	writeChroma()

	old, _ := filepath.Glob("assets/*")
	for _, f := range old {
		must(os.Remove(f))
	}
	must(os.MkdirAll("assets", 0o755))

	var m strings.Builder
	fmt.Fprintf(&m, "// Code generated by go generate. DO NOT EDIT.\n\npackage ui\n\n")
	fmt.Fprintf(&m, "// ShadcnTemplVersion 是生成资源时 go.mod 中 shadcn-templ 的版本。\nconst ShadcnTemplVersion = %q\n\n", version)
	core, extraFiles := bundle(dir)
	fmt.Fprintf(&m, "const scriptFile = %q\n\n", core)
	fmt.Fprintf(&m, "const glueFile = %q\n\n", glue())
	fmt.Fprintf(&m, "// extraScripts 是按需加载的组件脚本：页面出现选择器匹配的元素时，衔接脚本加载对应文件。\nvar extraScripts = map[string]string{\n")
	for _, e := range extras {
		fmt.Fprintf(&m, "\t%q: %q,\n", e.selector, extraFiles[e.dir])
	}
	fmt.Fprintf(&m, "}\n\n// stylesheets 是每套风格预编译的样式表。\nvar stylesheets = map[string]string{\n")
	for _, f := range styles {
		style := strings.TrimSuffix(strings.TrimPrefix(filepath.Base(f), "style-"), ".css")
		entry := fmt.Sprintf("css/style-%s.css", style)
		must(os.WriteFile(entry, fmt.Appendf(nil, "/* Code generated by go generate. DO NOT EDIT. */\n@import \"./ui.css\";\n@import \"./vendor/styles/style-%s.css\" layer(base);\n", style), 0o644))
		fmt.Fprintf(&m, "\t%q: %q,\n", style, tailwind(style))
	}
	fmt.Fprintf(&m, "}\n")
	src, err := format.Source([]byte(m.String()))
	must(err)
	must(os.WriteFile("manifest.go", src, 0o644))
	log.Printf("shadcn-templ %s: %s, %d extras, %d stylesheets", version, core, len(extras), len(styles))
}

// chromaSkip 是 chroma 样式中不需要的规则：背景用主题颜色（docs.css），不输出行号和高亮行。
var chromaSkip = []string{"Background", "PreWrapper", "Line", "LineLink", "LineTableTD", "LineTable", "LineHighlight", "LineNumbersTable", "LineNumbers", "CodeLine"}

// writeChroma 生成 css/docs-chroma.css：web/docs 代码块的高亮颜色，亮色是 chroma 的 github，暗色是 github-dark。
// 亮色的规则只在没有 .dark 时生效：暗色样式没有覆盖的 token 使用正文颜色，而不是亮色的深色。
func writeChroma() {
	f := chromahtml.New(chromahtml.WithClasses(true))
	var b strings.Builder
	b.WriteString("/* Code generated by go generate. DO NOT EDIT. */\n")
	for _, s := range []struct{ name, scope string }{{"github", ":where(html:not(.dark)) "}, {"github-dark", ".dark "}} {
		var css strings.Builder
		must(f.WriteCSS(&css, styles.Get(s.name)))
		for _, line := range strings.Split(css.String(), "\n") {
			name, rule, ok := strings.Cut(strings.TrimPrefix(line, "/* "), " */ ")
			if !ok || slices.Contains(chromaSkip, name) {
				continue
			}
			b.WriteString(s.scope + rule + "\n")
		}
	}
	must(os.WriteFile("css/docs-chroma.css", []byte(b.String()), 0o644))
}

// writeClasses 从组件源码（.templ、手写的 .go、.js）中提取空白和引号分隔的词，去重后写入 css/classes.txt。
// Tailwind 只需要类名候选，不需要源码；这样应用的 Tailwind 不必知道模块缓存中的路径。
func writeClasses(dir string) {
	files, _ := filepath.Glob(filepath.Join(dir, "components/*/*"))
	own, _ := filepath.Glob("*.templ")
	docs, _ := filepath.Glob("../docs/*.templ")
	panels, _ := filepath.Glob("../../queue/queueweb/*.templ") // 框架自带的运维面板
	own = append(append(own, docs...), panels...)
	seen := map[string]bool{}
	for _, f := range append(files, own...) {
		ext := filepath.Ext(f)
		if (ext != ".templ" && ext != ".go" && ext != ".js") || strings.HasSuffix(f, "_templ.go") || strings.HasSuffix(f, "_test.go") {
			continue
		}
		b, err := os.ReadFile(f)
		must(err)
		for _, w := range strings.FieldsFunc(string(b), func(r rune) bool {
			return r == ' ' || r == '\n' || r == '\t' || r == '"' || r == '`' || r == '\''
		}) {
			seen[w] = true
		}
	}
	words := make([]string, 0, len(seen))
	for w := range seen {
		words = append(words, w)
	}
	slices.Sort(words)
	must(os.WriteFile("css/classes.txt", []byte(strings.Join(words, "\n")+"\n"), 0o644))
}

// bundle 生成默认包和每个扩展组件的脚本，返回文件名。默认包与 shadcn-templ bundle 相同：
// baseui 在前（组件加载时向它注册），其余按文件名排序，逐个压缩后拼接。
func bundle(dir string) (string, map[string]string) {
	files, _ := filepath.Glob(filepath.Join(dir, "components/*/*.js"))
	files = slices.DeleteFunc(files, func(f string) bool { return strings.HasSuffix(f, ".min.js") })
	component := func(f string) string { return filepath.Base(filepath.Dir(f)) }
	slices.SortStableFunc(files, func(a, b string) int {
		switch {
		case component(a) == "baseui" && component(b) != "baseui":
			return -1
		case component(a) != "baseui" && component(b) == "baseui":
			return 1
		}
		return 0
	})
	var core bytes.Buffer
	parts := map[string]*bytes.Buffer{}
	for _, e := range extras {
		parts[e.dir] = &bytes.Buffer{}
	}
	for _, f := range files {
		data, err := os.ReadFile(f)
		must(err)
		rel, _ := filepath.Rel(dir, f)
		code := minify(filepath.ToSlash(rel), data)
		if b, ok := parts[component(f)]; ok {
			b.Write(code)
		} else {
			core.Write(code)
		}
	}
	names := map[string]string{}
	for _, e := range extras {
		js, err := os.ReadFile(filepath.Join(dir, "components", e.dir, e.dir+".js"))
		if err != nil || parts[e.dir].Len() == 0 {
			log.Fatalf("extra component %s has no script", e.dir)
		}
		tpl, _ := os.ReadFile(filepath.Join(dir, "components", e.dir, e.dir+".templ"))
		attr := []byte(strings.TrimPrefix(strings.Trim(e.selector, "[]"), "script["))
		if !bytes.Contains(js, attr) && !bytes.Contains(tpl, attr) {
			log.Fatalf("extra component %s: selector %s no longer appears in its .templ or script", e.dir, e.selector)
		}
		names[e.dir] = write("shadcn-templ-"+e.dir, ".js", parts[e.dir].Bytes())
	}
	return write("shadcn-templ", ".js", core.Bytes()), names
}

// glue 压缩衔接脚本 js/glue.js。
func glue() string {
	data, err := os.ReadFile("js/glue.js")
	must(err)
	return write("glue", ".js", minify("js/glue.js", data))
}

func minify(name string, data []byte) []byte {
	r := api.Transform(string(data), api.TransformOptions{
		Sourcefile: name, Loader: api.LoaderJS,
		MinifyWhitespace: true, MinifySyntax: true, MinifyIdentifiers: true,
		LegalComments: api.LegalCommentsInline, Charset: api.CharsetUTF8,
		Engines: []api.Engine{{Name: api.EngineChrome, Version: "111"}, {Name: api.EngineFirefox, Version: "113"}, {Name: api.EngineSafari, Version: "16.4"}},
	})
	if len(r.Errors) > 0 {
		log.Fatalf("%s: %s", name, r.Errors[0].Text)
	}
	return r.Code
}

// tailwind 编译风格入口 css/style-<style>.css 加上 safelist.css，返回文件名。
// source(none) 关闭自动扫描，只用 @source 列出的候选。
func tailwind(style string) string {
	entry := "css/.build.css"
	must(os.WriteFile(entry, []byte("@import \"tailwindcss\" source(none);\n@import \"./style-"+style+".css\";\n@import \"./safelist.css\";\n"), 0o644))
	defer os.Remove(entry)
	tmp := filepath.Join(os.TempDir(), "web-ui-"+style+".css")
	defer os.Remove(tmp)
	cmd := exec.Command("tailwindcss", "-i", entry, "-o", tmp, "--minify")
	cmd.Stderr = os.Stderr
	must(cmd.Run())
	b, err := os.ReadFile(tmp)
	must(err)
	return write("style-"+style, ".css", b)
}

// write 把 data 以 gzip 压缩写入 assets/<prefix>-<哈希><ext>.gz，返回不带 .gz 的文件名。
// gzip 头不含时间和文件名，同样的内容总是得到同样的文件。
func write(prefix, ext string, data []byte) string {
	sum := sha256.Sum256(data)
	name := fmt.Sprintf("%s-%x%s", prefix, sum[:8], ext)
	var buf bytes.Buffer
	zw, err := gzip.NewWriterLevel(&buf, gzip.BestCompression)
	must(err)
	_, err = zw.Write(data)
	must(err)
	must(zw.Close())
	must(os.WriteFile(filepath.Join("assets", name+".gz"), buf.Bytes(), 0o644))
	return name
}

func copyFile(from, to string) {
	b, err := os.ReadFile(from)
	must(err)
	must(os.WriteFile(to, b, 0o644))
}

func must(err error) {
	if err != nil {
		log.Fatal(err)
	}
}
