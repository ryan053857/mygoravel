// gen 从 go.mod 中固定版本的 shadcn-templ 生成 webui 的前端资源，在 webui 目录中运行：go run ./gen
//
//   - css/vendor/：上游的 tw-animate.css、shadcn-tailwind.css、8 套风格 styles/style-*.css，
//     以及从组件源码中提取的 class 候选 components.txt（Tailwind 扫描用）；
//   - css/style-<风格>.css：每套风格的样式入口，导入 ui.css 和该风格；
//   - assets/shadcn-templ-<哈希>.js：全部组件脚本，baseui 在前，逐个压缩后拼接，与 shadcn-templ bundle 相同；
//   - assets/style-<风格>-<哈希>.css：用 Tailwind 编译的风格入口，不需要应用安装 Tailwind；
//   - assets.go 中的文件名。
//
// 只有升级 shadcn-templ 或修改 css/ui.css 后需要运行，需要 tailwindcss（standalone CLI）。
package main

import (
	"bytes"
	"crypto/sha256"
	"fmt"
	"go/format"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"strings"

	"github.com/evanw/esbuild/pkg/api"
)

const module = "github.com/axadrn/shadcn-templ/v2"

func main() {
	out, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}} {{.Version}}", module).Output()
	if err != nil {
		log.Fatalf("go list %s: %v", module, err)
	}
	dir, version, _ := strings.Cut(strings.TrimSpace(string(out)), " ")

	must(os.RemoveAll("css/vendor"))
	must(os.MkdirAll("css/vendor/styles", 0o755))
	for _, f := range []string{"tw-animate.css", "shadcn-tailwind.css"} {
		copyFile(filepath.Join(dir, "assets/css", f), filepath.Join("css/vendor", f))
	}
	styles, _ := filepath.Glob(filepath.Join(dir, "assets/css/styles/style-*.css"))
	for _, f := range styles {
		copyFile(f, filepath.Join("css/vendor/styles", filepath.Base(f)))
	}
	writeClasses(dir)

	must(os.MkdirAll("assets", 0o755))
	old, _ := filepath.Glob("assets/*-*.*")
	for _, f := range old {
		must(os.Remove(f))
	}
	js := bundle(dir)
	var sheets strings.Builder
	for _, f := range styles {
		style := strings.TrimSuffix(strings.TrimPrefix(filepath.Base(f), "style-"), ".css")
		entry := fmt.Sprintf("css/style-%s.css", style)
		must(os.WriteFile(entry, []byte(fmt.Sprintf("/* Code generated by go run ./gen. DO NOT EDIT. */\n@import \"./ui.css\";\n@import \"./vendor/styles/style-%s.css\" layer(base);\n", style)), 0o644))
		fmt.Fprintf(&sheets, "\t%q: %q,\n", style, tailwind(style))
	}
	src := fmt.Sprintf(`// Code generated by go run ./gen. DO NOT EDIT.

package webui

// ShadcnTemplVersion 是生成资源时 go.mod 中 shadcn-templ 的版本。
const ShadcnTemplVersion = %q

const scriptFile = %q

// stylesheets 是每套风格预编译的样式表。
var stylesheets = map[string]string{
%s}
`, version, js, sheets.String())
	b, err := format.Source([]byte(src))
	must(err)
	must(os.WriteFile("assets.go", b, 0o644))
	log.Printf("shadcn-templ %s: %s and %d stylesheets", version, js, len(styles))
}

// writeClasses 从组件源码（.templ、手写的 .go、.js）中提取空白和引号分隔的词，去重后写入 components.txt。
// Tailwind 只需要类名候选，不需要源码本身；这样框架不必复制整份组件源码，
// 应用的 Tailwind 也不必知道模块缓存中的路径。
func writeClasses(dir string) {
	files, _ := filepath.Glob(filepath.Join(dir, "components/*/*"))
	seen := map[string]bool{}
	for _, f := range files {
		ext := filepath.Ext(f)
		if (ext != ".templ" && ext != ".go" && ext != ".js") || strings.HasSuffix(f, "_templ.go") || strings.HasSuffix(f, "_test.go") {
			continue
		}
		b, err := os.ReadFile(f)
		must(err)
		for _, w := range strings.FieldsFunc(string(b), func(r rune) bool {
			return r == ' ' || r == '\n' || r == '\t' || r == '"' || r == '`' || r == '\''
		}) {
			seen[w] = true
		}
	}
	words := make([]string, 0, len(seen))
	for w := range seen {
		words = append(words, w)
	}
	slices.Sort(words)
	must(os.WriteFile("css/vendor/components.txt", []byte(strings.Join(words, "\n")+"\n"), 0o644))
}

// bundle 与 shadcn-templ bundle 相同：baseui 的脚本在前（组件加载时向它注册），其余按文件名排序，逐个压缩后拼接。
func bundle(dir string) string {
	files, _ := filepath.Glob(filepath.Join(dir, "components/*/*.js"))
	files = slices.DeleteFunc(files, func(f string) bool { return strings.HasSuffix(f, ".min.js") })
	isBase := func(f string) bool { return filepath.Base(filepath.Dir(f)) == "baseui" }
	slices.SortStableFunc(files, func(a, b string) int {
		switch {
		case isBase(a) && !isBase(b):
			return -1
		case !isBase(a) && isBase(b):
			return 1
		}
		return 0
	})
	var sources, minified bytes.Buffer
	for _, f := range files {
		data, err := os.ReadFile(f)
		must(err)
		rel, _ := filepath.Rel(dir, f)
		sources.Write(data)
		r := api.Transform(string(data), api.TransformOptions{
			Sourcefile: filepath.ToSlash(rel), Loader: api.LoaderJS,
			MinifyWhitespace: true, MinifySyntax: true, MinifyIdentifiers: true,
			LegalComments: api.LegalCommentsInline, Charset: api.CharsetUTF8,
			Engines: []api.Engine{{Name: api.EngineChrome, Version: "111"}, {Name: api.EngineFirefox, Version: "113"}, {Name: api.EngineSafari, Version: "16.4"}},
		})
		if len(r.Errors) > 0 {
			log.Fatalf("%s: %s", rel, r.Errors[0].Text)
		}
		minified.Write(r.Code)
	}
	sum := sha256.Sum256(sources.Bytes())
	name := fmt.Sprintf("shadcn-templ-%x.js", sum[:8])
	must(os.WriteFile(filepath.Join("assets", name), minified.Bytes(), 0o644))
	return name
}

// tailwind 编译风格入口 css/style-<style>.css 加上 safelist.css。source(none) 关闭自动扫描，只用 @source 列出的候选。
func tailwind(style string) string {
	entry := "css/.build.css"
	must(os.WriteFile(entry, []byte("@import \"tailwindcss\" source(none);\n@import \"./style-"+style+".css\";\n@import \"./safelist.css\";\n"), 0o644))
	defer os.Remove(entry)
	tmp := "assets/build.css"
	cmd := exec.Command("tailwindcss", "-i", entry, "-o", tmp, "--minify")
	cmd.Stderr = os.Stderr
	must(cmd.Run())
	b, err := os.ReadFile(tmp)
	must(err)
	sum := sha256.Sum256(b)
	name := fmt.Sprintf("style-%s-%x.css", style, sum[:8])
	must(os.Rename(tmp, filepath.Join("assets", name)))
	return name
}

func copyFile(from, to string) {
	b, err := os.ReadFile(from)
	must(err)
	must(os.WriteFile(to, b, 0o644))
}

func must(err error) {
	if err != nil {
		log.Fatal(err)
	}
}
