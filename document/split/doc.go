// Package split 把 Markdown 切分为供检索使用的分段。
//
// 分段是输入中连续的字节区间，依次优先在块边界、换行、句末、分句标点和空白处切开，
// 中文和英文都在自然的位置断开。独立的标题是硬边界。每个分段带着它开始处所在的标题路径和表头，
// 以及它们的字节区间，调用方可以把它们作为算向量时的上下文，也能把每一段追溯到原文。
//
// # 长度
//
// 长度是码点数，CRLF 和单独的 CR 都算作一个 LF；无效 UTF-8 序列的每个字节算一个。
// Options 中的 Size、MaxSize、Overlap 和 Chunk.Length 都按这个标准计算，因此在 CRLF 输入上，
// Length 可能与 utf8.RuneCountInString(Text) 不同。切分器从不改写文本。
//
// # 保证
//
// 以下性质都有测试保证；具体在哪里切开不在兼容承诺之内，以后的版本可能改进。
//
//  1. 只有空白的输入得到 nil。否则第一段从 0 开始，最后一段在 len(input) 结束，Start 和 End 严格递增，
//     每段的开始不晚于上一段的结束（没有空隙）。
//  2. Text == input[Start:End]；任何偏移都不会落在一个 UTF-8 序列中间或 CRLF 的两个字节之间。
//  3. 依次拼接每段的 input[prev.End:c.End] 得到原输入。
//  4. 每段的 Length <= MaxSize。
//  5. 与上一段的重叠最多 Overlap，且尽力而为：在标题处、或重叠窗口内没有边界时为零。
//  6. 一段只在开头包含标题块，即一串连续的标题（中间可以有空行）。一串标题超过 MaxSize 时，
//     先在标题之间切开；单个标题超过 MaxSize 时在标题内部切开。
//  7. Headings 是分段第一个非空白字节（锚点）处生效的标题路径，不包括从锚点开始或包含锚点的标题。
//     因此从一个被切开的标题中间开始的分段只继承它的上级标题，这个标题本身从它正文的分段开始进入 Headings。
//
// # 偏好
//
// 在满足上述保证的前提下，按优先级：
//
//  1. 在标题块处切开。一串连续的标题放在一起，标题和它正文的开头放在一起，只要它们不超过 MaxSize。
//  2. 到下一个标题为止的文本不超过 MaxSize 时整段保留；否则分成长度接近 Size 的几段。
//  3. 在每一段的目标位置附近，选择级别最高的边界：块 > 换行 > 句末 > 分句标点 > 空白 > 封闭区域内 > 任意码点。
//     会切开字素簇的位置移到 MaxSize 以内较近的簇边界（距离相同时取后一个）。超过 Size 之后起初只考虑块边界；
//     只剩封闭区域内的边界或没有边界时，MaxSize 以内的换行、句末、分句标点或空白可以让一行或一个标题保持完整；
//     再不行，放得下的标题可以单独结束一段，不带正文的第一行。只要文本允许，每段至少 max(Overlap+1, Size/2) 长，
//     避免出现碎片。
//  4. 下一段从重叠窗口内级别最高、最靠前的边界开始，不从结尾的空白开始。
//  5. 每段都包含非空白的文本，除非它位于至少 Size 个码点的空白中，或者无法在 MaxSize 以内并入相邻的分段。
//
// 字素簇不借助 Unicode 属性表来近似判断：不会切在组合字符、零宽连接符、变体选择符、表情修饰符或标签字符之前，
// 不会切在零宽连接符之后，也不会切开国旗的两个区域指示符，除非一个簇的长度超出了 MaxSize。
// 其他连接方式（例如 U+200C 和谚文字母）不在其中，所以这不是完整的 UAX #29。
//
// 句末是 "。！？"，以及后面跟着空白的 ".!?"；分句标点是 "，；"，以及后面跟着空白的 ",;"。
// 相邻的两行文本，前一行以字母或数字结尾、后一行以字母、数字或句中标点开头时视为软换行，换行按空白计级。
// 软换行不会跨越空行或硬换行（行尾两个空格或 \）。
//
// 封闭区域（围栏和缩进代码、表格、HTML 块、front matter、行内代码）只提供换行边界；
// 只有单独一行超出预算时，才会切在行内。
//
// # Markdown 的识别范围
//
// 块结构由 goldmark 按 CommonMark 和 GFM 表格解析，与 goldmark 渲染时看到的结构一致。在此之上：
//
//   - LF、CRLF 和单独的 CR 都是换行（goldmark 本身不把单独的 CR 当作换行）。
//   - front matter：仅当第一行（可选的 BOM 之后）是 "---"、存在关闭的 "---" 或 "..." 行、
//     其间每一行都像 YAML（空行、缩进行、# 注释、"- " 列表项，或后跟 ":" 和空格或行尾的键），
//     并且至少有一行（缩进与否）是键；否则第一行是分隔线。只有列表项的块不是 front matter，
//     ATX 标题会被读作注释。front matter 之后的部分才交给 goldmark。
//   - 只有顶层的标题进入标题路径，只有顶层的表格提供 TableHeader；表头单元格全部为空的表格不提供。
//     引用块和列表项中的标题和表格只是容器的内容。
//   - 任何深度的围栏和缩进代码、表格和 HTML 块都是封闭区域。行内只识别代码段：同一行中长度相同的一对反引号串。
//
// 块边界位于标题之前、空行之后，以及进入或离开每个块（段落、列表项、引用块、代码、表格、HTML 块等）的位置。
//
// 为了在病态输入上保持线性，一行开头最多识别 32 层引用和列表标记、128 列缩进，一个段落最多 64 行
// 链接引用定义，表格补齐的空单元格最多是表格字节数的一半；超出的部分按文本处理。正常的文档碰不到这些上限。
//
// # 复杂度
//
// 扫描与输入长度成线性；每段最多检查 MaxSize 个位置来选择切点，所以在 MaxSize / Size 比例固定时
// 切分是线性的。工作内存约为每个输入字节 6 字节，再加上解析时的语法树：普通文档每字节十几字节，
// 全是很短的列表项时每字节一百多字节。超过 math.MaxInt32 字节的输入会 panic。
